-- ── updated_at maintenance ────────────────────────────────────────────────
-- The ORM sets updated_at client-side, but rows can also be written through
-- PostgREST or the dashboard, which bypass the ORM entirely. A trigger keeps
-- the column truthful regardless of the write path.
create or replace function set_updated_at() returns trigger as $$
begin
    new.updated_at = now();
    return new;
end;
$$ language plpgsql;

do $$
declare
    t text;
begin
    foreach t in array array[
        'ai_modes', 'daily_usage', 'knowledge_sources', 'memory_records',
        'projects', 'tool_integrations', 'activity_events', 'conversations',
        'messages'
    ] loop
        execute format('drop trigger if exists trg_%s_updated_at on %I', t, t);
        execute format(
            'create trigger trg_%s_updated_at before update on %I '
            'for each row execute function set_updated_at()', t, t);
    end loop;
end $$;
