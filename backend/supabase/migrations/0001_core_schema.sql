create table if not exists activity_events (
    id          bigint generated by default as identity primary key,
    label       text not null,
    mode_id     text not null,
    occurred_at timestamptz not null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create table if not exists conversations (
    id              text primary key,
    title           text not null,
    preview         text not null default '',
    mode_id         text not null,
    project_id      text,
    pinned          boolean not null default false,
    archived        boolean not null default false,
    message_count   integer not null default 0,
    last_message_at timestamptz,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);

create table if not exists messages (
    id              text primary key,
    conversation_id text not null,
    position        integer not null,   -- monotonic within a conversation
    role            text not null,
    mode_id         text not null,
    blocks          jsonb not null default '[]'::jsonb,
    reasoning       text,
    traces          jsonb,
    voice           boolean not null default false,
    tokens          integer,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);

-- ── Constraints ───────────────────────────────────────────────────────────
-- Added separately and guarded, because `create table if not exists` skips
-- the whole statement when the table already exists — including any inline
-- constraints — so an inline constraint would silently never appear on a
-- replay against a partially-created database.

do $$
begin
    alter table daily_usage add constraint uq_daily_usage_day unique (day);
exception when duplicate_table then null; when duplicate_object then null;
end $$;

do $$
begin
    alter table messages
        add constraint uq_messages_thread_pos unique (conversation_id, position);
exception when duplicate_table then null; when duplicate_object then null;
end $$;

do $$
begin
    alter table activity_events
        add constraint fk_activity_events_mode_id
        foreign key (mode_id) references ai_modes (id) on delete restrict;
exception when duplicate_object then null;
end $$;

do $$
begin
    alter table conversations
        add constraint fk_conversations_mode_id
        foreign key (mode_id) references ai_modes (id) on delete restrict;
exception when duplicate_object then null;
end $$;

do $$
begin
    alter table conversations
        add constraint fk_conversations_project_id
        foreign key (project_id) references projects (id) on delete set null;
exception when duplicate_object then null;
end $$;

do $$
begin
    alter table messages
        add constraint fk_messages_conversation_id
        foreign key (conversation_id) references conversations (id) on delete cascade;
exception when duplicate_object then null;
end $$;

do $$
begin
    alter table messages
        add constraint fk_messages_mode_id
        foreign key (mode_id) references ai_modes (id) on delete restrict;
exception when duplicate_object then null;
end $$;

