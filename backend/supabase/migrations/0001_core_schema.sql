-- AURELIS Intelligence API — Supabase core schema.
-- Migration 0001; follows the migration rules in ../README.md:
--   * idempotent (safe to replay)
--   * tables created without FKs so ordering never matters
--   * constraints, FKs and indexes added afterwards
--
-- This mirrors backend/alembic/versions/0001_module2_core_schema.py so the
-- Supabase deployment and the SQLite/Alembic deployment hold the same shape.

create table if not exists ai_modes (
    id          text primary key,
    label       text not null,
    caption     text not null,
    description text not null,
    aura        text not null,          -- "r g b" triple read by the UI's rgba() helper
    glyph       text not null,
    sort_order  integer not null default 0,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create table if not exists daily_usage (
    id         bigint generated by default as identity primary key,
    day        date not null,
    label      text not null,
    value      integer not null default 0,
    secondary  integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists knowledge_sources (
    id             text primary key,
    name           text not null,
    kind           text not null,       -- document | repository | dataset | feed
    status         text not null,       -- indexed | indexing | paused
    item_count     integer not null default 0,
    last_synced_at timestamptz,
    sort_order     integer not null default 0,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now()
);

create table if not exists memory_records (
    id          text primary key,
    statement   text not null,
    scope       text not null,
    confidence  double precision not null default 0,
    learned_at  timestamptz not null,
    owner_id    text,                   -- populated once MODULE 4 defines identity
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create table if not exists projects (
    id         text primary key,
    name       text not null,
    brief      text not null,
    progress   double precision not null default 0,
