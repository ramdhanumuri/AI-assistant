-- AURELIS Intelligence API — identity, sessions and the authentication audit.
-- Migration 0003; follows the rules in ../README.md:
--   * idempotent (safe to replay)
--   * tables created without FKs so ordering never matters
--   * constraints, FKs and indexes added afterwards
--
-- Mirrors backend/alembic/versions/0002_auth_identity.py so the Supabase
-- deployment and the SQLite/Alembic deployment hold the same shape.

-- ── Identity ──────────────────────────────────────────────────────────────
create table if not exists users (
    id                 uuid primary key default gen_random_uuid(),
    full_name          text not null,
    -- Stored lowercased and trimmed. The unique index below is what actually
    -- prevents duplicates; a check-then-insert alone would race.
    email              text not null,
    -- Argon2id encoded digest. Never a plaintext password, never reversible.
    password_hash      text not null,
    -- Server-owned. Never accepted from a request body.
    role               text not null default 'user',
    is_active          boolean not null default true,
    avatar_url         text,
    email_verified     boolean not null default false,
    last_login_at      timestamptz,
    failed_login_count integer not null default 0,
    locked_until       timestamptz,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),
    constraint ck_users_role check (role in ('user', 'admin'))
);

create table if not exists user_preferences (
    id            bigint generated by default as identity primary key,
    user_id       uuid not null,
    ambient_light boolean not null default true,
    particles     boolean not null default true,
    reduce_motion boolean not null default false,
    streaming     boolean not null default true,
    memory        boolean not null default true,
    citations     boolean not null default true,
    soundscape    boolean not null default false,
    density       text not null default 'comfortable',
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    constraint ck_user_preferences_density check (density in ('comfortable', 'compact'))
);

-- ── Sessions and reset tokens (digests only) ──────────────────────────────
-- Only the SHA-256 digest of a refresh token is stored, so a database leak
-- does not hand over usable tokens. Rotation and revocation are row updates.
create table if not exists auth_sessions (
    id           uuid primary key default gen_random_uuid(),
    user_id      uuid not null,
    token_hash   text not null,
    expires_at   timestamptz not null,
    revoked_at   timestamptz,
    last_used_at timestamptz,
    user_agent   text,
    -- HMAC digest of the client address, not the address itself.
    ip_hash      text,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);

create table if not exists password_reset_tokens (
    id         uuid primary key default gen_random_uuid(),
    user_id    uuid not null,
    token_hash text not null,
    expires_at timestamptz not null,
    used_at    timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- ── Audit trail ───────────────────────────────────────────────────────────
-- `user_id` carries no foreign key on purpose: the security record must
-- outlive the account it describes. Only keyed digests of the email and
-- address are stored, never the values.
create table if not exists auth_events (
    id          bigint generated by default as identity primary key,
    user_id     uuid,
    event_type  text not null,
    outcome     text not null default 'success',
    email_hash  text,
    ip_hash     text,
    user_agent  text,
    detail      text,
    occurred_at timestamptz not null default now(),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    constraint ck_auth_events_outcome check (outcome in ('success', 'failure', 'denied'))
);

