-- ── updated_at maintenance ────────────────────────────────────────────────
-- Reuses `set_updated_at()` from migration 0001, which is `create or replace`
-- there and so is guaranteed to exist by the time this file runs.
do $$
declare
    t text;
begin
    foreach t in array array[
        'users', 'user_preferences', 'auth_sessions',
        'password_reset_tokens', 'auth_events'
    ] loop
        execute format('drop trigger if exists trg_%s_updated_at on %I', t, t);
        execute format(
            'create trigger trg_%s_updated_at before update on %I '
            'for each row execute function set_updated_at()', t, t);
    end loop;
end $$;

-- ── Row Level Security ────────────────────────────────────────────────────
-- Enabled deny-by-default, matching migration 0002. `users` holds password
-- digests, so it is the last table that should ever be reachable from the
-- browser with the anon key.
alter table users                enable row level security;
alter table user_preferences     enable row level security;
alter table auth_sessions        enable row level security;
alter table password_reset_tokens enable row level security;
alter table auth_events          enable row level security;

revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

-- Reference data stays publicly readable so the SPA can theme itself before
-- login (re-asserted here because the blanket revoke above strips it again).
grant select on ai_modes to anon, authenticated;

